function makeTerm(
  attendance: number,
  quiz: number,
  labActivity: number | null,
  activity: number,
  exam: number,
  hasLab: boolean = true,
): DetailedTermScores {
  const computedTermGrade = computeTermGrade(
    { attendance, quiz, labActivity, activity, exam },
    hasLab,
  )
  return {
    attendance,
    quiz,
    labActivity,
    activity,
    exam,
    computedTermGrade,
    activities: activity,
    labExam: labActivity,
  }
}

