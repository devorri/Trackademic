function buildSheetEntry(
  studentId: string,
  studentName: string,
  studentNo: string,
  prelimScores: [number, number, number | null, number, number],
  midtermScores: [number, number, number | null, number, number],
  finalScores: [number, number, number | null, number, number],
  hasLab: boolean,
): DetailedGradingSheet {
  const prelim = makeTerm(...prelimScores, hasLab)
  const midterm = makeTerm(...midtermScores, hasLab)
  const final = makeTerm(...finalScores, hasLab)
  const average = computeOverallFromTerms(
    prelim.computedTermGrade,
    midterm.computedTermGrade,
    final.computedTermGrade,
  )
  let status: any = 'On Track'
  if (average >= 90) status = 'Excellent'
  else if (average >= 85) status = 'Good'
  else if (average >= 75) status = 'On Track'
  else if (average >= 70) status = 'At Risk'
  else status = 'Bound to Fail'

  return {
    studentId,
    studentName,
    studentNo,
    prelim,
    midterm,
    final,
    prelimExam: prelim.exam,
    quiz: prelim.quiz,
    activity: prelim.activity,
    attendance: prelim.attendance,
    labExam: prelim.labActivity,
    average,
    status,
  }
}

