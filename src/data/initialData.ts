function buildStudentSubjectRow(
  code: string,
  title: string,
  units: number,
  hasLaboratory: boolean,
  prelimScores: [number, number, number | null, number, number],
  midtermScores: [number, number, number | null, number, number],
  finalScores: [number, number, number | null, number, number],
) {
  const prelim = makeTerm(...prelimScores, hasLaboratory)
  const midterm = makeTerm(...midtermScores, hasLaboratory)
  const final = makeTerm(...finalScores, hasLaboratory)
  const subjectAverage = computeOverallFromTerms(
    prelim.computedTermGrade,
    midterm.computedTermGrade,
    final.computedTermGrade,
  )
  return {
    code,
    title,
    units,
    hasLaboratory,
    prelim,
    midterm,
    final,
    prelimExam: prelim.exam,
    quiz: prelim.quiz,
    activity: prelim.activity,
    attendance: prelim.attendance,
    participation: prelim.activity,
    labExam: prelim.labActivity,
    subjectAverage,
  }
}

